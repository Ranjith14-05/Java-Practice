public class MathFunc {
    public static void main(String[] args) {
        System.out.println("Absolute Value : "+ Math.abs(-40));
        System.out.println("Round of Value : "+ Math.round(2.56));
        System.out.println("Floor Of Value : "+ Math.floor(2.56));
        System.out.println("Ceil Value : "+ Math.ceil(2.06));

        int a = 10;
        int b = 20;

        System.out.println("Maximum of a & b : "+Math.max(a, b));
        System.out.println("Square Root : "+ Math.sqrt(4));
        System.out.println("Power of : "+ Math.pow(a, 2));

        System.out.println("The");
    }
}
